import { expect, test, type Page } from '@playwright/test'
import { fakeAppLock, mockServer, signIn, VIEWPORTS, type MockServer } from './fixtures'
import { BASE, seedPortfolio } from './swingMock'

const rail = (page: Page) => page.getByRole('navigation', { name: 'Main' })

async function openSwing(page: Page, setup?: (state: MockServer) => void) {
  const state = await mockServer(page)
  setup?.(state)
  await signIn(page)
  await rail(page).getByRole('button', { name: 'Swing' }).click()
  return state
}
const seeded = (state: MockServer) => seedPortfolio(state.swing)
const sent = (state: MockServer, suffix: string, method = 'POST') => state.swing.requests.filter(r => r.method === method && r.path === `${BASE}${suffix}`)
const sheet = (page: Page, name: string | RegExp) => page.getByRole('dialog', { name })

test('with no portfolio the Swing tab offers to start one, and starting shows an empty book', async ({ page }) => {
  const state = await openSwing(page)
  await expect(page.getByRole('heading', { name: 'Start a paper swing portfolio' })).toBeVisible()
  await page.getByLabel('Starting capital ₹').fill('500000')
  await page.getByRole('button', { name: 'Start portfolio' }).click()
  await expect(page.getByText('No open positions')).toBeVisible()
  expect(sent(state, '')[0].body).toMatchObject({ mode: 'paper', capital: 500000, paper_broker: 'kite' })
  await expect(page.getByRole('button', { name: 'New order' })).toBeEnabled()
})

