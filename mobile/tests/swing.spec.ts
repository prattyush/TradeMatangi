test.describe('real money', () => {
  test('is not offered until the App lock is on, and nothing real is requested before that', async ({ page }) => {
    await fakeAppLock(page) // the phone has a screen lock, but the app lock is off
    const state = await openSwing(page)
    await page.getByRole('button', { name: 'Real', exact: true }).click()
    await expect(page.getByText('Turn on the App lock to trade real money')).toBeVisible()
    expect(state.swing.requests.some(r => r.query.get('mode') === 'real')).toBe(false)
    expect(sent(state, '', 'POST')).toHaveLength(0)
  })

  test('with the App lock on, the phone lock is asked, then the real portfolio opens with REAL in large type on every order', async ({ page }) => {
    await fakeAppLock(page)
    const state = await mockServer(page)
    seedPortfolio(state.swing, 'real')
    state.swing.orders = []
    await signIn(page)
    await rail(page).getByRole('button', { name: 'More' }).click()
    await page.getByRole('switch').check()
    await rail(page).getByRole('button', { name: 'Swing' }).click()
    const before = await page.evaluate(() => (window as unknown as { __lockCalls: number }).__lockCalls)
    await page.getByRole('button', { name: 'Real', exact: true }).click()
    await expect.poll(() => page.evaluate(() => (window as unknown as { __lockCalls: number }).__lockCalls)).toBe(before + 1)
    await expect(page.getByRole('list', { name: 'Positions' })).toBeVisible()
    expect(state.swing.requests.some(r => r.query.get('mode') === 'real')).toBe(true)
    await page.getByRole('listitem', { name: 'HDFCBANK Long 100' }).click()
    await expect(sheet(page, 'HDFCBANK').getByRole('status').first()).toContainText('REAL MONEY')
    await sheet(page, 'HDFCBANK').getByRole('button', { name: 'Exit' }).click()
    await sheet(page, 'New order').getByRole('button', { name: 'Review order' }).click()
    const review = sheet(page, 'Review order')
    await expect(review.getByRole('status').first()).toContainText('REAL MONEY order')
    await review.getByRole('button', { name: 'Place REAL order' }).click()
    expect(sent(state, '/pf-real/orders')[0].body).toMatchObject({ client: 'phone', side: 'SELL' })
  })

  test('a cancelled phone-lock prompt leaves the app on paper', async ({ page }) => {
    await fakeAppLock(page)
    const state = await mockServer(page)
    await signIn(page)
    await rail(page).getByRole('button', { name: 'More' }).click()
    await page.getByRole('switch').check()
    await page.evaluate(() => { (window as unknown as { __lockMode: string }).__lockMode = 'cancelled' })
    await rail(page).getByRole('button', { name: 'Swing' }).click()
    await page.getByRole('button', { name: 'Real', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Paper', exact: true })).toHaveAttribute('aria-pressed', 'true')
    expect(state.swing.requests.some(r => r.query.get('mode') === 'real')).toBe(false)
  })

  test('an account without real-trading access is told so', async ({ page }) => {
    await fakeAppLock(page)
    const state = await mockServer(page)
    state.swing.realAllowed = false
    await signIn(page)
    await rail(page).getByRole('button', { name: 'More' }).click()
    await page.getByRole('switch').check()
    await rail(page).getByRole('button', { name: 'Swing' }).click()
    await page.getByRole('button', { name: 'Real', exact: true }).click()
    await expect(page.getByText('Your account has no real-trading access.')).toBeVisible()
  })

  test('starting a real portfolio needs the broker session to be connected', async ({ page }) => {
    await fakeAppLock(page)
    const state = await mockServer(page)
    state.swing.brokerConnected = false
    await signIn(page)
    await rail(page).getByRole('button', { name: 'More' }).click()
    await page.getByRole('switch').check()
    await rail(page).getByRole('button', { name: 'Swing' }).click()
    await page.getByRole('button', { name: 'Real', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('session is not connected')
    await expect(page.getByRole('button', { name: 'Start REAL portfolio' })).toBeDisabled()
  })
})

for (const viewport of VIEWPORTS) {
  test(`the Swing screen and its ticket fit at ${viewport.name} with finger-sized buttons`, async ({ page }) => {
    await page.setViewportSize({ width: viewport.width, height: viewport.height })
    await openSwing(page, seeded)
    const fits = () => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)
    expect(await fits()).toBe(true)
    for (const name of ['New order', 'Refresh']) expect((await page.getByRole('button', { name }).boundingBox())!.height).toBeGreaterThanOrEqual(36)
    expect((await page.getByRole('button', { name: 'New order' }).boundingBox())!.height).toBeGreaterThanOrEqual(44)
    const items = rail(page).getByRole('button')
    await expect(items).toHaveCount(6)
    for (const item of await items.all()) expect((await item.boundingBox())!.height).toBeGreaterThanOrEqual(44)
    await page.getByRole('button', { name: 'New order' }).click()
    const ticket = sheet(page, 'New order')
    await expect(ticket).toBeVisible()
    expect(await fits()).toBe(true)
    // The ticket scrolls inside the sheet and keeps its Review button reachable.
    await ticket.getByRole('button', { name: 'Review order' }).scrollIntoViewIfNeeded()
    expect((await ticket.getByRole('button', { name: 'Review order' }).boundingBox())!.height).toBeGreaterThanOrEqual(44)
    await page.screenshot({ path: `test-results/swing-ticket-${viewport.name}.png` })
  })
}
