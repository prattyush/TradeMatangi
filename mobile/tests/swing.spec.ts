test('no answer or a broker problem keeps the same request id, so pressing Confirm again cannot place twice', async ({ page }) => {
  const state = await openSwing(page, s => { seeded(s); s.swing.orders = []; s.swing.failNextOrder = { status: 502, detail: 'Broker placement needs review' } })
  await page.getByRole('listitem', { name: 'HDFCBANK Long 100' }).click()
  await sheet(page, 'HDFCBANK').getByRole('button', { name: 'Exit' }).click()
  await sheet(page, 'New order').getByRole('button', { name: 'Review order' }).click()
  const review = sheet(page, 'Review order')
  await review.getByRole('button', { name: 'Place paper order' }).click()
  await expect(review.getByRole('alert').first()).toContainText('Not sure whether this went through')
  await expect(review.getByRole('alert').nth(1)).toContainText('cannot be placed twice')
  await review.getByRole('button', { name: 'Place paper order' }).click()
  await expect(sheet(page, 'Review order')).toHaveCount(0)
  const orders = sent(state, '/pf-paper/orders')
  expect(orders).toHaveLength(2)
  expect((orders[0].body as { request_id: string }).request_id).toBe((orders[1].body as { request_id: string }).request_id)
  expect(state.swing.orders).toHaveLength(1)
})

