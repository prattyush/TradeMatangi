import { expect, test, type Page } from '@playwright/test'
import { mockWorkspace } from './workspaceFixture'
const app = 'http://127.0.0.1:5175/webapp/'
const exit = (page: Page) => page.locator('.webapp-fullscreen-exit')
async function fullWorkspace(page: Page) {
  await expect(page.locator('.webapp-bar')).toHaveCount(0)
  await expect(page.getByText('TradeMatangi app', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Install app', exact: true })).toHaveCount(0)
  expect(await page.locator('.webapp-workspace').evaluate(element => {
    const rect = element.getBoundingClientRect()
    return rect.top === 0 && Math.abs(rect.height - innerHeight) < 1
  })).toBe(true)
}

test('fullscreen exit reveals at the top edge without a row and preserves the mounted charts', async ({ page }) => {
  await mockWorkspace(page)
  await page.goto(app)
  await expect(page.locator('canvas').first()).toBeVisible()
  const canvas = await page.locator('canvas').first().elementHandle()
  await fullWorkspace(page)
  const header = page.locator('.website-header')
  expect((await header.boundingBox())!.y).toBe(0)
  await header.getByRole('button', { name: 'Full screen', exact: true }).click()
  await expect.poll(() => page.evaluate(() => Boolean(document.fullscreenElement))).toBe(true)
  await expect(header.locator('.app-fullscreen-button')).toBeHidden()
  await expect(exit(page)).toHaveCSS('opacity', '0')
  await fullWorkspace(page)
  await page.evaluate(() => window.dispatchEvent(new Event('beforeinstallprompt')))
  await expect(page.getByRole('button', { name: 'Install app', exact: true })).toHaveCount(0)
  await page.mouse.move(200, 4)
  await expect(exit(page)).toHaveCSS('opacity', '1')
  await exit(page).hover()
  await page.waitForTimeout(1700) // Longer than the auto-hide deadline: hover must pin it.
  await expect(exit(page)).toHaveCSS('opacity', '1')
  await page.mouse.move(200, 250)
  await expect(exit(page)).toHaveCSS('opacity', '0', { timeout: 3000 })
  await exit(page).focus()
  await page.waitForTimeout(1700)
  await expect(exit(page)).toHaveCSS('opacity', '1')
  await exit(page).click()
  await expect.poll(() => page.evaluate(() => Boolean(document.fullscreenElement))).toBe(false)
  await expect(exit(page)).toHaveCount(0)
  await expect(header.getByRole('button', { name: 'Full screen', exact: true })).toBeVisible()
  await fullWorkspace(page)
  expect(await canvas!.evaluate(element => element.isConnected)).toBe(true)
  await header.getByRole('button', { name: 'Full screen', exact: true }).click()
  await expect(header.locator('.app-fullscreen-button')).toBeHidden()
  await expect.poll(() => page.evaluate(() => Boolean(document.fullscreenElement))).toBe(true)
  await page.keyboard.press('Escape')
  await expect.poll(() => page.evaluate(() => Boolean(document.fullscreenElement))).toBe(false)
  expect(await canvas!.evaluate(element => element.isConnected)).toBe(true)
  await header.getByRole('button', { name: 'Full screen', exact: true }).click()
  await page.evaluate(() => document.exitFullscreen())
  await expect(header.getByRole('button', { name: 'Full screen', exact: true })).toBeVisible()
})

test('touch users restore from the existing header without a window bar', async ({ browser }) => {
  const context = await browser.newContext({ hasTouch: true, viewport: { width: 1024, height: 768 } })
  try {
    const page = await context.newPage()
    await mockWorkspace(page)
    await page.goto(app)
    const control = page.locator('.website-header .app-fullscreen-button')
    await control.tap()
    await expect(control).toHaveAttribute('aria-label', 'Exit full screen')
    await expect(control).toBeVisible()
    await fullWorkspace(page)
    await expect(exit(page)).toHaveCSS('opacity', '0')
    await control.tap()
    await expect(control).toHaveAttribute('aria-label', 'Full screen')
    await fullWorkspace(page)
  } finally { await context.close() }
})

test('login and main app pages reuse their own existing fullscreen control areas', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(app)
  await expect(page.getByRole('button', { name: 'Full screen', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Install app', exact: true })).toHaveCount(0)
  await mockWorkspace(page)
  await page.reload()
  await page.getByRole('button', { name: /Patterns/ }).click()
  await expect(page.getByRole('button', { name: 'Full screen', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '← Back to Trading', exact: true }).click()
  await page.getByRole('button', { name: /Structures/ }).click()
  await expect(page.getByRole('button', { name: 'Full screen', exact: true }).last()).toBeVisible()
  await page.getByRole('button', { name: '✕ Close', exact: true }).click()
  await page.getByRole('button', { name: /Analysis/ }).click()
  await expect(page.getByRole('button', { name: 'Full screen', exact: true }).last()).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'Swing', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Full screen', exact: true })).toBeVisible()
  await fullWorkspace(page)
  expect(errors).toEqual([])
})
